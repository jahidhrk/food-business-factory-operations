import {readFileSync,writeFileSync} from 'node:fs';
import ts from 'typescript';
const sources=['lib/catalog.ts','lib/engine.ts','lib/demo-accounts.ts','supabase/handler.ts'];
const input=sources.map(file=>readFileSync(file,'utf8').replace(/^import .*?;\n/gm,'')).join('\n');
const output=ts.transpileModule(input,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022,removeComments:false}}).outputText;
writeFileSync('supabase/functions/factory-api/index.ts','// Generated by npm run build:backend. Paste this ENTIRE file into the Supabase dashboard editor.\n'+output);
console.log('Generated single-file Supabase function.');
